#!/usr/bin/env python3
"""Saved results: a student saves an assessment, lists, reads and deletes it."""

import sys

from common import (Api, run_module, unique_email, strong_password, browser_page,
                    goto, ui_login, assessment_payload)

SUITE = "saved-results"


def sample_result():
    return {
        "gwa": "Very Satisfactory",
        "honors": "No Honors",
        "competencies": "Critical Thinking, Information Technology Skills",
        "dominantCode": "ICR",
        "clarityLabel": "High Career Clarity",
        "clarityBucket": "High",
        "clarityTotal": 19.5,
        "predictedOutcome": "ICT-Aligned",
        "predictedConfidence": 0.8123,
        "aiAnalysis": "PERSONALITY PROFILE\nGenerated by the end-to-end test.",
        "notes": "e2e test row",
    }


def run(cfg, report, api):
    report.suite = SUITE

    student = Api(cfg.base_url)
    email, password = unique_email("saver"), strong_password()
    status, reg = student.register(email, password, "E2E Saver")
    if not report.check("student account created", status == 200, str(reg)[:160]):
        return

    report.section("Empty to start")
    status, rows = student.get("/api/results")
    report.check("list returns 200", status == 200, str(status))
    report.check("a new student has no saved results", rows == [], str(rows)[:120])

    report.section("Saving a result")
    status, saved = student.post("/api/results", sample_result())
    if not report.check("save returns 200", status == 200, str(saved)[:160]):
        return

    result_id = saved["id"]
    report.check("the saved row gets an id", isinstance(result_id, int) and result_id > 0, str(result_id))
    report.check("the saved row is timestamped", bool(saved.get("createdAt")))
    report.check("the dominant code round-trips", saved["dominantCode"] == "ICR", saved["dominantCode"])
    report.check("the prediction round-trips",
                 saved["predictedOutcome"] == "ICT-Aligned" and abs(saved["predictedConfidence"] - 0.8123) < 1e-4,
                 f"{saved['predictedOutcome']} {saved['predictedConfidence']}")
    report.check("the clarity total round-trips", abs(saved["clarityTotal"] - 19.5) < 1e-6, str(saved["clarityTotal"]))
    report.check("the AI analysis round-trips", "PERSONALITY PROFILE" in saved["aiAnalysis"])
    report.check("the note round-trips", saved["notes"] == "e2e test row", saved["notes"])

    report.section("Reading it back")
    status, rows = student.get("/api/results")
    report.check("the list now holds one row", status == 200 and len(rows) == 1, f"{status} {len(rows)}")
    status, one = student.get(f"/api/results/{result_id}")
    report.check("fetching by id returns the same row", status == 200 and one["id"] == result_id, str(status))

    status, missing = student.get("/api/results/99999999")
    report.check("an unknown id returns 404", status == 404, str(status))

    report.section("Results are private to their owner")
    other = Api(cfg.base_url)
    other_email = unique_email("other")
    status, _ = other.register(other_email, strong_password(), "E2E Other")
    if report.check("second student account created", status == 200, str(status)):
        status, other_rows = other.get("/api/results")
        report.check("the second student sees none of the first student's rows",
                     status == 200 and other_rows == [], str(other_rows)[:120])
        status, _ = other.get(f"/api/results/{result_id}")
        report.check("the second student cannot read the row by id", status == 404, str(status))
        status, _ = other.delete(f"/api/results/{result_id}")
        report.check("the second student cannot delete the row", status == 404, str(status))

    status, _ = api.get("/api/results")
    report.check("an anonymous caller cannot list results", status in (401, 403), str(status))

    report.section("Second save and delete")
    status, second = student.post("/api/results", {**sample_result(), "notes": "second row"})
    report.check("a student can save more than one result", status == 200, str(status))
    status, rows = student.get("/api/results")
    report.check("the list holds both rows", len(rows) == 2, str(len(rows)))
    report.check("the newest row is listed first",
                 rows[0]["id"] == second["id"], f"{[r['id'] for r in rows]}")

    status, _ = student.delete(f"/api/results/{result_id}")
    report.check("delete returns 204", status == 204, str(status))
    status, rows = student.get("/api/results")
    report.check("the deleted row is gone", len(rows) == 1 and rows[0]["id"] == second["id"], str(len(rows)))
    status, _ = student.delete(f"/api/results/{result_id}")
    report.check("deleting an already-deleted row returns 404", status == 404, str(status))

    # Leave nothing behind.
    student.delete(f"/api/results/{second['id']}")

    if cfg.api_only:
        return

    report.section("My Saved Results page")
    student.post("/api/results", {**sample_result(), "notes": "row for the UI check"})
    with browser_page(cfg, report, SUITE) as page:
        if not ui_login(page, cfg, email, password, report):
            return
        goto(page, cfg, "/my-results")
        page.wait_for_timeout(2500)
        text = page.inner_text("body")
        report.check("the saved row is listed on the page", "ICT-Aligned" in text, text[:120])
        report.check("the row shows the RIASEC code and clarity",
                     "ICR" in text and "High Career Clarity" in text, "")
        report.check("the row shows the prediction confidence", "81% confidence" in text, "")

        # The detail lives in a collapsed expansion panel.
        page.locator(".mud-expand-panel-header").first.click()
        page.wait_for_timeout(1000)
        detail = page.inner_text(".mud-expand-panel")
        report.check("expanding the row shows the saved competencies", "Critical Thinking" in detail, "")
        report.check("expanding the row shows the clarity total", "19.5/25" in detail.replace(" ", ""), "")
        # The saved narrative is split into the same sections as the live report,
        # so the heading becomes the note's title and the body sits under it.
        # Note titles are uppercased in CSS and inner_text() returns rendered text.
        lowered = detail.lower()
        report.check("expanding the row shows the AI analysis under its section title",
                     "what your interests say" in lowered
                     and "generated by the end-to-end test" in lowered, "")
        # Notes are stored and returned by the API but the page does not render
        # them today; asserting on the fields the page actually shows instead.

    status, rows = student.get("/api/results")
    for row in rows:
        student.delete(f"/api/results/{row['id']}")


if __name__ == "__main__":
    sys.exit(run_module(run, __doc__))
